CREATE TABLE Regulations (
  Id INT IDENTITY PRIMARY KEY,
  Code VARCHAR(20) NOT NULL UNIQUE,
  Name NVARCHAR(100) NOT NULL,
  IsActive BIT NOT NULL DEFAULT 1
);

CREATE TABLE Courses (
  Id INT IDENTITY PRIMARY KEY,
  Code VARCHAR(20) NOT NULL UNIQUE,
  Title NVARCHAR(200) NOT NULL,
  RegulationId INT NOT NULL REFERENCES Regulations(Id),
  IsActive BIT NOT NULL DEFAULT 1
);

CREATE TABLE SyllabusUnits (
  Id INT IDENTITY PRIMARY KEY,
  CourseId INT NOT NULL REFERENCES Courses(Id) ON DELETE CASCADE,
  UnitNo INT NOT NULL,
  Title NVARCHAR(200) NOT NULL,
  CoText NVARCHAR(500) NOT NULL,
  Topics NVARCHAR(MAX) NOT NULL,
  UNIQUE (CourseId, UnitNo)
);