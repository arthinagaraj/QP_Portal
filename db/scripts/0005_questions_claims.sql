CREATE TABLE BankDetails (
  UserId INT PRIMARY KEY REFERENCES Users(Id),
  AccountHolder NVARCHAR(120) NOT NULL,
  AccountNumber VARCHAR(18) NOT NULL,
  BankName NVARCHAR(100) NOT NULL,
  Branch NVARCHAR(100) NULL,
  Ifsc VARCHAR(11) NOT NULL,
  Pan VARCHAR(10) NOT NULL,
  Address NVARCHAR(400) NOT NULL,
  UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE Questions (
  Id INT IDENTITY PRIMARY KEY,
  AssignmentId INT NOT NULL REFERENCES Assignments(Id),
  PartName VARCHAR(5) NOT NULL,
  QNo INT NOT NULL,
  OptionLetter VARCHAR(1) NOT NULL DEFAULT '',
  UnitNo INT NOT NULL,
  BodyHtml NVARCHAR(MAX) NOT NULL,
  PlainText NVARCHAR(MAX) NOT NULL,
  Marks DECIMAL(5,1) NOT NULL,
  Btl VARCHAR(2) NOT NULL,
  BtlSource VARCHAR(10) NOT NULL DEFAULT 'AI',
  MatchScore DECIMAL(4,2) NOT NULL DEFAULT 0,
  SyllabusVerdict VARCHAR(5) NOT NULL DEFAULT 'Out',
  Clarity VARCHAR(10) NOT NULL DEFAULT 'Incomplete',
  AiNotes NVARCHAR(1000) NULL,
  UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  UNIQUE (AssignmentId, PartName, QNo, OptionLetter)
);

